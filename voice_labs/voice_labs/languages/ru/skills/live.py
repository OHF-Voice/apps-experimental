"""Whether a Russian question is about now or here -- погода, новости,
счёт матча, цены, что открыто (voice_labs/skills/live.py).

Read lowercase with "ё" as "е" ("ещё" as "еще"). "Утра" or "вечера" is a
time of day, not the weather; "в этом году" is left to the dates ("когда
Пасха в этом году")."""

from __future__ import annotations

import re

from .numbers import fold

LIVE_PATTERNS = [
    (r"\b(погод\w*|прогноз\w*|дожд\w*|снег\w*|снежн\w*|солнечн\w*|облачн\w*|пасмурн\w*|ветер|ветр\w*|гроз\w*|град|"
     r"мороз\w*|влажност\w*|зонт\w*|куртк\w*|пальто|ультрафиолет\w*|качество воздуха|пыльц\w*|туман\w*)\b"),
    r"\b(на улице|за окном|снаружи)\b",
    r"\b(восход\w*|закат\w*|рассвет\w*|прилив\w*|отлив\w*)\b",
    r"\b(новост\w*|заголовк\w*|что нового|что случилось|что произошло)\b",
    (r"\b(сч[её]т матча|результат\w* матча|турнирн\w* таблиц\w*|кто выиграл|кто победил|кто ведет|"
     r"кто играет|следующий матч|по телевизору|по телику)\b"),
    (r"\b(сейчас|сегодня|сегодняшн\w*|завтра|завтрашн\w*|вчера|вчерашн\w*|послезавтра|позавчера|на этой неделе|"
     r"в эти выходные|на выходных|в данный момент|на данный момент|пока что)\b"),
    r"\bкто (?:сейчас )?(?:президент|премьер|мэр|губернатор|канцлер|король|королева|папа римский)\b",
    r"\b(цен[аыуе]|цены|стоит|стоят|стоимость|курс\w*|акци\w*|биткоин\w*|крипт\w*|бензин\w*|ставк\w* по ипотеке)\b",
    r"\b(рядом|поблизости|недалеко|рядом со мной|в моем районе|возле меня|ближайш\w*)\b",
    (r"\b(открыт\w*|откроется|открывается|закрыт\w*|закроется|закрывается|работает|работают|часы работы|"
     r"режим работы)\b.*\b(магазин\w*|супермаркет\w*|ресторан\w*|кафе|аптек\w*|банк\w*|библиотек\w*|почт\w*|"
     r"торгов\w* центр\w*)\b"),
    (r"\b(магазин\w*|супермаркет\w*|ресторан\w*|кафе|аптек\w*|банк\w*|библиотек\w*|почт\w*|торгов\w* центр\w*)\b"
     r".*\b(открыт\w*|откроется|открывается|закрыт\w*|закроется|закрывается|работает|работают)\b"),
    r"\b(мой|следующий) рейс\b|\bрейс\w* (?:задерживается|задержан|отменен|по расписанию)\b",
    r"\b(пробк\w*|затор\w*|задержк\w*|авари\w*|отключени\w* (?:света|воды))\b",
    # The time now (not "который час будет через 45 минут после 15": the clock skill's).
    (r"^(?:который (?:сейчас )?час|сколько (?:сейчас )?времени|какое (?:сегодня )?число|какой (?:сегодня )?день"
     r"(?: недели)?|какая (?:сегодня )?дата)\s*[?.!]*\s*$"),
]
# Words that look live but are not, in questions that never change.
LIVE_EXCEPTIONS = [
    r"\bчто (?:значит|означает)\b.*",
    r"\bкак (?:правильно )?(?:пишется|написать|пишут)\b.*",
    r"\bпо буквам\b.*",
    r"\b(?:переменн\w*|постоянн\w*|электрическ\w*) ток\w*\b",
    r"\b(?:утра|вечера|ночи|дня)\b",
    # A weight in pounds is not money.
    r"\b(?:килограмм\w*|кило|грамм\w*|унци\w*|тонн\w*)\b.*\bфунт\w*\b",
]
_CURRENCIES = re.compile(r"\b(евро|доллар\w*|рубл\w*|фунт\w* стерлинг\w*|иен\w*|йен\w*|юан\w*|песо)\b")


def _currency(word: str) -> str:
    """"долларов" and "доллар" are one currency."""
    return word[:4]


def is_live(q):
    s = re.sub(r"[,;]", " ", fold(q))
    for p in LIVE_EXCEPTIONS:
        s = re.sub(p, " ", s)
    s = " ".join(s.split())
    # Two currencies: an exchange rate ("сколько рублей в долларе").
    if len({_currency(c) for c in _CURRENCIES.findall(s)}) > 1:
        return True
    return any(re.search(p, s) for p in LIVE_PATTERNS)
