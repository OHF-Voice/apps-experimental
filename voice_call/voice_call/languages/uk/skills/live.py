"""Whether a Ukrainian question is about now or here -- погода, новини,
рахунок, ціни, що відкрито (voice_call/skills/live.py).

"Останній" alone is no sign of it: "остання неділя травня" is a date; nor is
"ранку" in "о сьомій ранку"."""

from __future__ import annotations

import re

from .numbers import apostrophes

LIVE_PATTERNS = [
    r"\b(погода|погоди|погоду|погодою|прогноз|прогнозу|дощ|дощу|дощик|злива|сніг|снігу|сонячно|хмарно|вітер|вітру|гроза|грози|град|ожеледиця|вологість|парасольк\w*|куртк\w*|ультрафіолет|якість повітря|пилок)\b",
    r"\b(температура надворі|на вулиці|надворі|за вікном)\b",
    r"\b(схід сонця|захід сонця|світанок|світанку|сутінки|приплив|відплив)\b",
    r"\b(новини|новин|заголовки|що сталося|що відбувається)\b",
    r"\b(рахунок|результат матчу|результати|турнірна таблиця|наступний матч|по телевізору|по телеку)\b",
    r"\bхто (?:виграв|переміг|виграє|перемагає|веде)\b",
    r"\b(зараз|наразі|нині|сьогодні|завтра|вчора|учора|післязавтра|позавчора|цього тижня|на вихідних|цього року|в цей момент|на даний момент)\b",
    r"\bхто (?:зараз )?(?:є )?(президент|прем'єр|прем'єр-міністр|мер|король|королева|папа)\b",
    r"\b(ціна|ціни|коштує|коштують|курс|курс валют|курс долара|курс євро|акції|біткоїн|крипт\w*|бензин|пальне)\b",
    r"\b(поблизу|поруч|біля мене|неподалік|у моєму районі)\b",
    r"\b(відкрит\w*|відчинен\w*|працює|зачинен\w*|закрит\w*|розклад|години роботи)\b.*\b(магазин|супермаркет|ресторан|аптека|аптеку|банк|бібліотека|пошта|пошту|торговий центр|кафе)\b",
    r"\b(магазин|супермаркет|ресторан|аптека|аптеку|банк|бібліотека|пошта|пошту|торговий центр|кафе)\b.*\b(відкрит\w*|відчинен\w*|працює|зачинен\w*|закрит\w*|розклад|години роботи)\b",
    r"\b(мій|наступний) рейс\b|\bрейс (затримується|за розкладом|скасовано)\b",
    r"\b(затор|затори|пробк\w*|відключення світла|графік відключень|світло дадуть|тривога|повітряна тривога)\b",
    # The time now (not "котра година буде через 45 хвилин після третьої": the clock skill's).
    r"\bкотра (?:зараз )?година\s*[?.!]*\s*$|\bскільки (?:зараз )?часу\s*[?.!]*\s*$|\bяке (?:сьогодні )?число\s*[?.!]*\s*$",
]
LIVE_EXCEPTIONS = [
    r"\bщо означає\b.*",
    r"\bяк (?:пишеться|правильно написати|написати|сказати по буквах)\b.*",
    r"\bпостійний струм\b|\bзмінний струм\b",
    r"\b(?:ранку|вечора|ночі|дня)\b",
]
_CURRENCIES = re.compile(r"\b(гривн\w*|долар\w*|євро|фунт\w* стерлінг\w*|злот\w*|єн[аи]?)\b")


def _currency(word: str) -> str:
    """"доларів" and "долар" are one currency."""
    return word[:4]


def is_live(q):
    s = re.sub(r"[,;]", " ", apostrophes(q.lower()))
    for p in LIVE_EXCEPTIONS:
        s = re.sub(p, " ", s)
    # Two currencies: an exchange rate ("скільки гривень за один долар").
    if len({_currency(c) for c in _CURRENCIES.findall(s)}) > 1:
        return True
    return any(re.search(p, s) for p in LIVE_PATTERNS)
